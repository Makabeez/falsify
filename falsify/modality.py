"""Same claim, two formats: does a screenshot give the same rules and verdict as the pasted text?

For a corpus claim with an image in corpus/raw/<id>.png (a page screenshot: chart plus the description),
this runs the full pipeline on the image alone. Muse Spark transcribes it, quotes are checked against
that transcript, and the rest is unchanged. The result is set next to the text run in corpus/results
and both are scored against the trader-reviewed reference in corpus/ground_truth.yaml.

    falsify modality run                 # every corpus/raw/c*.png that has a corpus record
    falsify modality report --out docs/modality.md
"""

from __future__ import annotations

import json
import time
from pathlib import Path

from .battery import attach_fidelity, attach_grounding, falsify
from .corpus import _note, load
from .groundtruth import GT_PATH, conditions_match, from_spec_condition, load_reference, score_claim

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "corpus" / "raw"
OUT = ROOT / "corpus" / "modality"
RESULTS = ROOT / "corpus" / "results"
CLAIMS = ROOT / "corpus" / "claims.jsonl"
EXIT_KEYS = ("stop_loss_pct", "stop_atr_mult", "take_profit_pct", "take_profit_atr_mult", "take_profit_r",
             "trailing_stop_pct", "trailing_stop_atr_mult", "max_hold_bars")


def run(ids: list[str] | None = None, raw: Path = RAW, out: Path = OUT, model: str | None = None) -> None:
    from .extract import Source, compile_and_audit, fidelity
    recs = {r["id"]: r for r in load(CLAIMS)}
    images = sorted(p for p in raw.glob("c*.png") if p.stem in recs and (not ids or p.stem in ids))
    out.mkdir(parents=True, exist_ok=True)
    print(f"modality {len(images)} screenshot(s)")
    for img in images:
        rec, t0 = recs[img.stem], time.time()
        res: dict = {"id": img.stem, "image": img.name}
        try:
            # The note carries only page context (source type, post date), never quotable text.
            spec, audit, trace = compile_and_audit(Source.from_path(str(img), note=_note(rec)), model=model)
            rep = falsify(spec, posted=rec.get("posted"))
            attach_grounding(rep, trace.get("grounding"))
            attach_fidelity(rep, fidelity(spec, audit))
            res.update(spec=spec.model_dump(mode="json"), audit=audit.model_dump(mode="json"),
                       transcript=trace.get("transcript"), grounding=trace.get("grounding"),
                       cost=trace.get("cost"), report=rep.to_dict())
        except Exception as e:
            res["error"] = f"{type(e).__name__}: {e}"[:500]
        res["seconds"] = round(time.time() - t0, 1)
        (out / f"{img.stem}.json").write_text(json.dumps(res, indent=1, default=str), encoding="utf-8")
        print(f"  {img.stem}  {res.get('report', {}).get('verdict') or res.get('error')}  ({res['seconds']}s)")


def same_rules(a: dict, b: dict) -> list[str]:
    """Where two compiled specs differ ([] = same rules)."""
    diffs = []
    if bool(a.get("testable")) != bool(b.get("testable")):
        return ["testable"]
    if not a.get("testable"):
        return []
    for k in ("timeframe", "direction"):
        if a.get(k) != b.get(k):
            diffs.append(k)
    if set(a.get("assets", [])) != set(b.get("assets", [])):
        diffs.append("assets")
    for part in ("entry", "exit"):
        ca = [from_spec_condition(c) for c in a.get(part, [])]
        cb = [from_spec_condition(c) for c in b.get(part, [])]
        if not conditions_match(ca, cb, lenient=False):
            diffs.append(part + (" (same meaning)" if conditions_match(ca, cb, lenient=True) else ""))
    for k in EXIT_KEYS:
        if a.get(k) != b.get(k):
            diffs.append(k)
    return diffs


def _score(cid: str, ref: dict, d: dict) -> str:
    if cid not in ref:
        return "no reference"
    s = score_claim(cid, ref[cid], d["spec"], d["report"]["verdict"])
    right = sum(s.fields.values())
    wrong = [k for k, v in s.fields.items() if not v]
    return f"{right}/{len(s.fields)}" + (f" (off: {', '.join(wrong)})" if wrong else "")


def report(out: Path = OUT, gt_path: Path = GT_PATH) -> str:
    ref = load_reference(gt_path)
    lines = ["# Same claim, two formats", "",
             "Generated by `falsify modality report`. Each row is one corpus claim run twice through the same "
             "pipeline: once from the pasted text, once from a page screenshot (chart plus description, nothing "
             "else). For the screenshot, Muse Spark transcribes the image first and the quote check runs against "
             "that transcript. Both runs are scored against the trader-reviewed reference.", "",
             "| Claim | Text verdict | Screenshot verdict | Text vs. trader | Screenshot vs. trader | Rules identical? "
             "| Screenshot quotes |",
             "|---|---|---|---|---|---|---|"]
    notes = []
    for f in sorted(out.glob("c*.json")):
        img = json.loads(f.read_text(encoding="utf-8"))
        txt_path = RESULTS / f.name
        if "error" in img or not txt_path.exists():
            lines.append(f"| {img['id']} | | {img.get('error', 'no text run')[:60]} | | | | |")
            continue
        txt = json.loads(txt_path.read_text(encoding="utf-8"))
        diffs = same_rules(txt["spec"], img["spec"])
        g = img.get("grounding") or {}
        q = f"{g.get('quoted', 0)}/{g.get('rule_elements', 0)}" if g.get("rule_elements") else "-"
        lines.append(f"| {img['id']} | {txt['report']['verdict']} | {img['report']['verdict']} | "
                     f"{_score(img['id'], ref, txt)} | {_score(img['id'], ref, img)} | "
                     f"{'yes' if not diffs else 'no: ' + ', '.join(diffs)} | {q} |")
        tr = (img.get("transcript") or {}).get("chart")
        if tr:
            notes.append(f"- **{img['id']}**: what Muse Spark saw in the chart: {tr}")
    if notes:
        lines += ["", "## What the model read off the charts", "", *notes]
    return "\n".join(lines) + "\n"
